'use strict';
const assert = require('assert'); const crypto = require('crypto');
const { canon, intentOf } = require('./canon');
const { createSigner } = require('./signer');
const { evaluate } = require('./policy'); const { decode } = require('./decoder');
const policy = require('./policy.json');
const H = s => crypto.createHash('sha256').update(s).digest('hex');
const TX = { kind: 'pay', action: 'Pay 0.50 SOL', to: 'Alice1111111111111111111111111111111111111', amountSol: 0.5, meta: { memo: 'demo', tip: 0 } };
let pass = 0, fail = 0;
const t = (n, f) => { try { f(); pass++; console.log('PASS', n); } catch (e) { fail++; console.log('FAIL', n, e.message); } };
function run(signTx, passDigestOfSigned = false) {
  const s = createSigner({ digestOf: H }); const d = H(intentOf(TX));
  s.attest({ challengeHex: 'c0ffee', intentDigest: d, confidence: 1 });
  // attacker passes the ATTESTED digest with a different tx (caller-trust attack) unless told otherwise
  return s.sign({ tx: signTx, challengeHex: 'c0ffee', intentDigest: passDigestOfSigned ? H(intentOf(signTx)) : d });
}
const R = r => assert.ok(!r.ok && /REFUSED/.test(r.error), JSON.stringify(r));
t('legit AUTHORIZED', () => assert.ok(run(TX).ok));
t('legit, keys shuffled AUTHORIZED', () => assert.ok(run({ meta: { tip: 0, memo: 'demo' }, amountSol: 0.5, to: TX.to, action: TX.action, kind: 'pay' }).ok));
t('amountSol swap REFUSED', () => R(run({ ...TX, amountSol: 9 })));
t('recipient swap REFUSED', () => R(run({ ...TX, to: 'Mallory111' })));
t('nested meta.tip swap REFUSED', () => R(run({ ...TX, meta: { ...TX.meta, tip: 999 } })));
t('field injection REFUSED', () => R(run({ ...TX, evil: true })));
t('nested injection REFUSED', () => R(run({ ...TX, meta: { ...TX.meta, x: 1 } })));
t('type confusion "0.5" REFUSED', () => R(run({ ...TX, amountSol: '0.5' })));
t('honest-digest-of-swapped-tx REFUSED', () => R(run({ ...TX, amountSol: 9 }, true)));
t('Date collapse REFUSED (not "{}")', () => R(run({ ...TX, meta: { ...TX.meta, at: new Date(0) } })));
t('undefined field throws', () => assert.throws(() => canon({ a: undefined })));
t('NaN throws', () => assert.throws(() => canon({ a: NaN })));
t('sparse array throws', () => assert.throws(() => canon([1, , 3])));
t('array order matters', () => assert.notStrictEqual(canon([1, 2]), canon([2, 1])));
t('__proto__ key via JSON.parse is bound', () => assert.notStrictEqual(canon(JSON.parse('{"__proto__":{"a":1}}')), canon({})));
t('single use: 2nd sign REFUSED', () => { const s = createSigner({ digestOf: H }); const d = H(intentOf(TX)); s.attest({ challengeHex: 'c', intentDigest: d, confidence: 1 }); assert.ok(s.sign({ tx: TX, challengeHex: 'c', intentDigest: d }).ok); R(s.sign({ tx: TX, challengeHex: 'c', intentDigest: d })); });
t('policy: 0.05 to Alice AUTO', () => assert.strictEqual(evaluate(policy, { ...TX, amountSol: 0.05 }).verdict, 'AUTO'));
t('policy: 0.5 to Alice TAP', () => assert.strictEqual(evaluate(policy, TX).verdict, 'TAP'));
t('policy: allowance exhausted TAP', () => assert.strictEqual(evaluate(policy, { ...TX, amountSol: 0.05 }, 0.22).verdict, 'TAP'));
t('policy: drain TAP + decoder line', () => { const tx = { kind: 'drain', to: 'Mallory1111111111111', amountSol: 10 }; const o = evaluate(policy, tx);
  assert.strictEqual(o.verdict, 'TAP'); const line = decode(tx, policy, { verdict: 'BLOCKED', reason: 'no tap — phone was not at the stone.' }); console.log('   decoder:', line); assert.ok(/EVERYTHING/.test(line)); });
t('drain without ceremony: signer REFUSED', () => R(createSigner({ digestOf: H }).sign({ tx: { kind: 'drain' }, challengeHex: 'x', intentDigest: 'y' })));
console.log(`\n${pass}/${pass + fail} pass`); process.exit(fail ? 1 : 0);
